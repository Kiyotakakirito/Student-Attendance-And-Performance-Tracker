package com.example.studenttracker.data.network

data class DashboardCounts(val students: Int, val faculty: Int, val subjects: Int, val departments: Int)
data class DashboardResponse(val dashboard: DashboardCounts)
data class StudentResponse(val student: Student)
data class FacultyResponse(val facultyMember: Faculty)
data class SubjectResponse(val subject: Subject)
data class RosterStudent(val studentId: String, val name: String)
data class RosterResponse(val students: List<RosterStudent>, val revision: Int)
data class EnrollmentRequest(val subjectCode: String, val studentIds: List<String>, val revision: Int, val action: String = "saveEnrollment")
data class AttendanceEntry(val studentId: String, val status: String)
data class AttendanceRequest(val subjectCode: String, val date: String, val slot: String, val requestId: String, val records: List<AttendanceEntry>, val action: String = "saveAttendance")
data class MarkEntry(val studentId: String, val status: String, val score: Double? = null, val name: String = "")
data class Assessment(val assessmentId: String, val subjectCode: String, val title: String, val maxMarks: Double, val marks: List<MarkEntry>, val published: Boolean, val revision: Int)
data class AssessmentsResponse(val assessments: List<Assessment>)
data class AssessmentRequest(val assessmentId: String, val subjectCode: String, val title: String, val maxMarks: Double, val marks: List<MarkEntry>, val published: Boolean, val revision: Int, val requestId: String, val action: String = "saveAssessment")
data class AssessmentResponse(val message: String, val assessment: Assessment)
data class SubjectAttendance(val subjectCode: String, val subjectName: String, val totalPresent: String, val totalClasses: String, val percentage: String)
data class StudentResult(val assessmentId: String, val title: String, val subjectCode: String, val maxMarks: Double, val score: Double?, val status: String)
data class ProgressResponse(val attendance: List<SubjectAttendance>, val results: List<StudentResult>)
